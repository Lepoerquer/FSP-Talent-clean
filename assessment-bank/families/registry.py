def get_family_meta(code: str) -> ItemFamilyMeta:
    """Retrieve metadata for an item family code."""
    if code not in FAMILIES_METADATA:
        raise KeyError(f"Unknown item family code: {code}")
    return FAMILIES_METADATA[code]


def render_family_item(code: str, seed: int) -> ItemRenderResult:
    """Render an isomorphic item instance for the given family and random seed."""
    if code not in GENERATORS:
        raise KeyError(f"No generator registered for family code: {code}")
    return GENERATORS[code](seed)


def list_all_families() -> list[ItemFamilyMeta]:
    """Return list of all registered item families."""
    return list(FAMILIES_METADATA.values())


def export_yaml_specs(output_dir: str) -> None:
    """Export YAML specification files for all registered families."""
    os.makedirs(output_dir, exist_ok=True)
    for code, meta in FAMILIES_METADATA.items():
        spec = {
            "code": meta.code,
            "specialization": meta.specialization,
            "target_grade": meta.target_grade,
            "topic": meta.topic,
            "item_format": meta.item_format,
            "discrimination_a": meta.discrimination_a,
            "difficulty_b": meta.difficulty_b,
            "description": meta.description,
        }
        filepath = os.path.join(output_dir, f"{code.lower()}.yaml")
        with open(filepath, "w", encoding="utf-8") as f:
            yaml.dump(spec, f, allow_unicode=True, sort_keys=False)
